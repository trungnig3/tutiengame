/**
 * Trả về bộ kỹ năng trang bị khởi đầu tương ứng với Linh Căn người chơi nhận được
 */
export function getInitialSkillsForRoot(rootElement: string): Skill[] {
  const dashSkill = DEFAULT_SKILLS.find(s => s.id === 'skill_dash')!;
  const slashSkill = DEFAULT_SKILLS.find(s => s.id === 'skill_slash')!;
  const vanKiemSkill = DEFAULT_SKILLS.find(s => s.id === 'skill_van_kiem')!;
  const hoiXuanSkill = DEFAULT_SKILLS.find(s => s.id === 'skill_hoi_xuan')!;
  const phiKiemSkill = DEFAULT_SKILLS.find(s => s.id === 'skill_phi_kiem')!;
  const loiDongSkill = DEFAULT_SKILLS.find(s => s.id === 'skill_loi_dong')!;
  const hoaCauSkill = DEFAULT_SKILLS.find(s => s.id === 'skill_hoa_cau')!;
  const viemBaoSkill = DEFAULT_SKILLS.find(s => s.id === 'skill_viem_bao')!;
  const bangTienSkill = DEFAULT_SKILLS.find(s => s.id === 'skill_bang_tien')!;
  const diaChanSkill = DEFAULT_SKILLS.find(s => s.id === 'skill_dia_chan')!;

  if (rootElement === 'hoa') {
    return [
      { ...slashSkill, element: 'hoa', name: 'Xích Viêm Trảm' },
      { ...dashSkill },
      { ...hoaCauSkill },
      { ...viemBaoSkill },
      { ...vanKiemSkill, element: 'hoa', name: 'Viêm Long Phần Thiên' },
    ];
  }

  if (rootElement === 'thuy' || rootElement === 'bang') {
    return [
      { ...slashSkill, element: 'thuy', name: 'Hàn Băng Kiếm Trảm' },
      { ...dashSkill },
      { ...bangTienSkill },
      { ...hoiXuanSkill, name: 'Huyền Thủy Dưỡng Linh Thuật' },
      { ...vanKiemSkill, element: 'thuy', name: 'Băng Vũ Thiên Phong' },
    ];
  }

  if (rootElement === 'tho') {
    return [
      { ...slashSkill, element: 'tho', name: 'Trọng Nham Trảm' },
      { ...dashSkill },
      { ...phiKiemSkill, element: 'tho', name: 'Huyền Thiết Phi Tiêu' },
      { ...diaChanSkill },
      { ...vanKiemSkill, element: 'tho', name: 'Kim Chung Bất Hoại Trận' },
    ];
  }

  if (rootElement === 'loi') {
    return [
      { ...slashSkill, element: 'loi', name: 'Tử Điện Kiếm Trảm' },
      { ...dashSkill },
      { ...phiKiemSkill, element: 'loi', name: 'Lôi Âm Phi Kiếm' },
      { ...loiDongSkill },
      { ...vanKiemSkill, element: 'loi', name: 'Cửu Tiêu Lôi Trận' },
    ];
  }

  if (rootElement === 'moc') {
    return [
      { ...slashSkill, element: 'moc', name: 'Thanh Mộc Kiếm Khí' },
      { ...dashSkill },
      { ...phiKiemSkill },
      { ...hoiXuanSkill },
      { ...vanKiemSkill, element: 'moc', name: 'Vạn Diệp Quy Tông' },
    ];
  }

  // Mặc định Kim hoặc Ngũ Hành
  return [
    { ...slashSkill },
    { ...dashSkill },
    { ...phiKiemSkill },
    { ...loiDongSkill },
    { ...vanKiemSkill },
    { ...hoiXuanSkill },
  ];
}

